#!/usr/bin/env python3
"""Write the hand-off file for AI coding agents from a QA audit.json.

Usage: python build_handoff.py audit.json out/qa-handoff.md

The human report (index.html) is for people; this file is for the agent that
will implement the fixes: plain Markdown, YAML front matter, no design, one
fact per line, every task with location, steps, expected/actual, evidence,
fix, the test that proves it and who has to act. Same order and ids as the
report (BUG-01 = bug #1). Standard library only.
"""
import json
import os
import re
import sys

SEV = ["blocker", "critical", "major", "minor", "trivial"]
OWNER = {
    "code": "Agent can do it in code (theme, plugin code, templates, config in the repo)",
    "admin": "Needs CMS / tool admin access (WordPress admin, GTM, GA4, Search Console, hosting panel)",
    "decision": "Needs a decision or wording from the site owner before anyone changes it",
}
VERDICT = ["blocks-release", "fix-before-next-deploy", "fix-in-backlog", "ready"]


def strip(s):
    """Drop report-only markup: [[red]] highlights."""
    return re.sub(r"\[\[(.+?)\]\]", r"\1", str(s or "")).strip()


def ice(b):
    return b["I"] * b["C"] * b["E"]


def ordered(bugs):
    idx = list(range(1, len(bugs) + 1))
    return sorted(idx, key=lambda i: (SEV.index(bugs[i - 1]["sev"]), -ice(bugs[i - 1]), i))


def yaml_val(v):
    if isinstance(v, list):
        return "[" + ", ".join(yaml_val(x) for x in v) + "]"
    s = str(v)
    return json.dumps(s, ensure_ascii=False) if re.search(r"[:#\[\]{},&*!|>'\"%@`]|^\s|\s$", s) or s == "" else s


def owner_of(b, d):
    o = d.get("owner")
    if o in OWNER:
        return o
    return "code"


def render(a):
    bugs = a.get("bugs") or []
    detail = a.get("detail") or {}
    tests = {t["id"]: t for t in a.get("tests") or []}
    suite = {c["id"]: c for c in (a.get("suite") or {}).get("checks", [])}
    tg = a.get("target") or {}
    order = ordered(bugs)
    nc = [x.get("n") or x.get("k") for x in a.get("areas", []) if x.get("s") is None]
    L = []
    fm = {
        "type": "qa-handoff",
        "schema": 1,
        "site": tg.get("url", ""),
        "environment": tg.get("env", ""),
        "deploy": tg.get("deploy", ""),
        "audited": tg.get("date", ""),
        "verdict": VERDICT[a["verdict"]["cur"]] if a.get("verdict") else "",
        "stack": a.get("stack") or [],
        "tasks": len(bugs),
        "by_severity": {s: sum(1 for b in bugs if b["sev"] == s) for s in SEV if any(b["sev"] == s for b in bugs)},
        "not_checked": nc,
        "tests_dir": "qa-tests/" if a.get("suite") else "",
        "tests_run": "cd qa-tests && npm install && npx playwright install chromium && npx playwright test" if a.get("suite") else "",
        "report": "index.html",
    }
    L.append("---")
    for k, v in fm.items():
        if isinstance(v, dict):
            L.append(f"{k}:")
            for kk, vv in v.items():
                L.append(f"  {kk}: {vv}")
        else:
            L.append(f"{k}: {yaml_val(v)}")
    L.append("---")
    L.append("")
    L.append(f"# QA hand-off: {tg.get('url') or a.get('title', '')}")
    L.append("")
    L.append("Task list for an implementing agent, generated by the qa-audit skill. The human report (`index.html`) has the same findings with charts and screenshots; ids match (BUG-01 = #1 there).")
    L.append("")
    L.append("## Rules for the agent")
    L.append("")
    rules = [
        "Work in the order below (severity, then ICE). One commit or PR per BUG id; put the id in the message.",
        "Never submit real forms, payments or messages on production, and never send test events into production analytics. Use the synthetic checks in `qa-tests/`.",
        "Tasks marked `owner: decision` need the site owner's answer first: ask, do not guess business facts (prices, terms, legal text, which language versions to keep).",
        "Tasks marked `owner: admin` happen in an admin UI (CMS, GTM, GA4, Search Console, hosting). If you have no access, prepare the exact change and hand it to a human.",
        "Status `hypothesis` means: reproduce first. If it does not reproduce, report that and skip the fix.",
        "A task is done only when its **Done when** line holds and its test passes. Then rerun the whole suite to catch regressions.",
    ]
    for r in rules:
        L.append(f"- {r}")
    if nc:
        L.append(f"- Not checked in this audit (do not assume they are fine): {', '.join(nc)}.")
    L.append("")

    # summary table
    L.append("## Tasks")
    L.append("")
    L.append("| ID | Severity | Area | Status | Owner | Test | Title |")
    L.append("|---|---|---|---|---|---|---|")
    for i in order:
        b, d = bugs[i - 1], detail.get(str(i), {})
        L.append(f"| BUG-{i:02d} | {b['sev']} | {b['l']} | {'observed' if b['ev'] == 'obs' else 'hypothesis'} | {owner_of(b, d)} | {d.get('test') or '-'} | {strip(b['t']).replace('|', '/')} |")
    L.append("")

    for group in ("code", "admin", "decision"):
        ids = [i for i in order if owner_of(bugs[i - 1], detail.get(str(i), {})) == group]
        if not ids:
            continue
        L.append(f"## {OWNER[group]}")
        L.append("")
        for i in ids:
            b, d = bugs[i - 1], detail.get(str(i), {})
            L.append(f"### BUG-{i:02d} · {b['sev']} · {b['l']} · {'observed' if b['ev'] == 'obs' else 'hypothesis — verify first'}")
            L.append("")
            L.append(f"Title: {strip(b['t'])}")
            L.append(f"Type: {b['x']} · ICE {ice(b)} (I{b['I']} C{b['C']} E{b['E']})")
            w = b.get("where")
            if w:
                if isinstance(w, dict):
                    for k in ("url", "selector", "file", "template", "plugin", "setting", "tool"):
                        if w.get(k):
                            L.append(f"Where ({k}): `{w[k]}`" if k in ("selector", "file") else f"Where ({k}): {w[k]}")
                else:
                    L.append(f"Where: {w}")
            if d.get("env"):
                L.append(f"Environment: {strip(d['env'])}")
            L.append("")
            if d.get("steps"):
                L.append("Reproduce:")
                for n, s in enumerate(d["steps"], 1):
                    L.append(f"{n}. {strip(s)}")
                L.append("")
            L.append(f"Expected: {strip(d.get('exp'))}")
            L.append(f"Actual: {strip(d.get('act'))}")
            ev = d.get("evid") or []
            if ev:
                L.append("Evidence:")
                for e in ev:
                    t = strip(e.get("t"))
                    L.append(f"- {e.get('k')}: {t}" + (f" (file: `{e['src']}`)" if e.get("src") else ""))
            L.append("")
            if d.get("fix"):
                L.append("Fix:")
                for n, s in enumerate(d["fix"], 1):
                    L.append(f"{n}. {strip(s)}")
            if d.get("code"):
                L.append("")
                L.append("Suggested change:")
                L.append("")
                lang = d.get("codeLang", "")
                L.append(f"```{lang}")
                L.append(d["code"].rstrip())
                L.append("```")
            if d.get("alt"):
                L.append("")
                L.append("Options considered:")
                for s in d["alt"]:
                    L.append(f"- {strip(s)}")
            L.append("")
            done = d.get("thr") or (a.get("plans", {}).get(str(i), {}) or {}).get("m")
            t = d.get("test")
            if done:
                L.append(f"Done when: {strip(done)}")
            if t:
                c = suite.get(t, {})
                L.append(f"Test: `{t}` ({c.get('type', '')}) — {strip(tests.get(t, {}).get('t', ''))}. Run: `QA_ONLY={t} npx playwright test`")
            else:
                L.append("Test: none automated; verify by hand with the steps above.")
            L.append(f"Owner action: {OWNER[owner_of(b, d)]}")
            if d.get("risk"):
                L.append(f"Risk: {strip(d['risk'])}")
            if d.get("pm"):
                L.append(f"Pre-mortem: {strip(d['pm'])}")
            L.append("")

    cl = a.get("checklist") or []
    if cl:
        L.append("## Post-deploy checklist (state at audit time)")
        L.append("")
        mark = {"pass": "x", "fail": " ", "warn": "~", "nc": "?"}
        for c in cl:
            L.append(f"- [{mark.get(c['st'], ' ')}] {strip(c['t'])} — {c['st']}" + (f": {strip(c['note'])}" if c.get("note") else ""))
        L.append("")
    if tests:
        L.append("## Tests")
        L.append("")
        L.append("| ID | Checks | Area | At audit |")
        L.append("|---|---|---|---|")
        for t in a.get("tests"):
            L.append(f"| {t['id']} | {strip(t['t']).replace('|', '/')} | {t['area']} | {t['st']} |")
        L.append("")
    src = a.get("sources") or []
    if src:
        L.append("## Sources used")
        L.append("")
        for s in src:
            L.append(f"- {strip(s['name'])}: {s['status']} ({strip(s.get('note'))})")
        L.append("")
    return "\n".join(L).rstrip() + "\n"


def write_handoff(audit, out):
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    md = render(audit)
    with open(out, "w", encoding="utf-8") as f:
        f.write(md)
    return out


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    with open(sys.argv[1], encoding="utf-8") as f:
        a = json.load(f)
    print("Written", write_handoff(a, sys.argv[2]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
